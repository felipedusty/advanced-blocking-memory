"""Build hosts-format block lists and a config that uses them, to exercise the app's BlockList parser.

The lab's main config uses ad-block lists (`||domain^`), so the parser of hosts and plain domain lists
(`BlockList.ReadListFile`) only sees the small allow lists and the edge fixtures there. This script rewrites
the names of the real lists in the formats that parser accepts and writes `lab/config/dnsApp.hosts.config`.

    python3 lab/make-hosts-lists.py
    APP_CONFIG=lab/config/dnsApp.hosts.config LAB_CONFIG=dnsApp.hosts.config ...   # then the usual lab scripts

The files are written to lab/lists/ under the sha256 of their URL, like lab/fetch-lists.sh does; run it after
fetch-lists.sh. Line styles cycle through `0.0.0.0 name`, `127.0.0.1 name`, bare `name`, `0.0.0.0 name # note`,
a leading `*.`, upper case, comments, loopback lines and a repeated name, so the parser's branches all run.
"""

import hashlib
import json
import os

SOURCE_CONFIG = "lab/config/dnsApp.config"
TARGET_CONFIG = "lab/config/dnsApp.hosts.config"
BIG_LIST_LIMIT = 300_000  # names taken from the biggest list


def adblock_names(path):
    names = []
    with open(path, encoding="utf-8", errors="replace") as f:
        for raw in f:
            line = raw.rstrip("\r\n").lstrip(" \t")
            if not line.startswith("||"):
                continue
            rest = line[2:]
            i = rest.find("^")
            if i > -1 and rest[i + 1 :] == "":
                names.append(rest[:i])
    return names


def hosts_lines(names):
    out = [
        "# generated by lab/make-hosts-lists.py",
        "127.0.0.1 localhost",
        "::1 localhost ip6-localhost",
        "",
    ]
    for i, name in enumerate(names):
        style = i % 8
        if style == 0:
            out.append(f"0.0.0.0 {name}")
        elif style == 1:
            out.append(f"127.0.0.1\t{name}")
        elif style == 2:
            out.append(name)
        elif style == 3:
            out.append(f"0.0.0.0 {name} # note")
        elif style == 4:
            out.append(f"*.{name}")
        elif style == 5:
            out.append(f"0.0.0.0 {name.upper()}")
        elif style == 6:
            out.append(f"  {name}  ")
        else:
            out.append(f"0.0.0.0 {name}")
            out.append(f"0.0.0.0 {name}")
        if i % 5000 == 0:
            out.append(f"# section {i}")
    return "\n".join(out) + "\n"


def main():
    with open(SOURCE_CONFIG, encoding="utf-8") as f:
        config = json.load(f)

    group = next(g for g in config["groups"] if g.get("adblockListUrls"))
    sources = []
    for url in group["adblockListUrls"]:
        if isinstance(url, dict):
            url = url["url"]
        path = os.path.join("lab/lists", hashlib.sha256(url.encode()).hexdigest())
        if not os.path.exists(path):
            raise SystemExit(f"missing {path}; run lab/fetch-lists.sh")
        sources.append((url, path))

    sources.sort(key=lambda item: os.path.getsize(item[1]), reverse=True)
    block_urls = []
    for rank, (url, path) in enumerate(sources[:8]):
        names = adblock_names(path)
        if rank == 0:
            names = names[:BIG_LIST_LIMIT]
        host_url = "https://lab.test/hosts/" + url.rsplit("/", 1)[1]
        with open(
            os.path.join("lab/lists", hashlib.sha256(host_url.encode()).hexdigest()),
            "w",
            encoding="utf-8",
        ) as f:
            f.write(hosts_lines(names))
        block_urls.append(host_url)
        print(f"{host_url}: {len(names)} names")

    group["adblockListUrls"] = []
    group["blockListUrls"] = block_urls
    with open(TARGET_CONFIG, "w", encoding="utf-8") as f:
        json.dump(config, f, indent=2)
        f.write("\n")

    print(f"wrote {TARGET_CONFIG}")


if __name__ == "__main__":
    main()
